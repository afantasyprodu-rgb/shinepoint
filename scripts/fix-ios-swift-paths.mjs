// The Capacitor CLI writes ios/App/CapApp-SPM/Package.swift using the host
// OS's path separator. On Windows that means backslashes inside the Swift
// string literals — e.g. `path: "..\..\..\node_modules\@capacitor\app"`.
// Swift string literals treat backslash as an escape character: `\n` there
// is a newline, and `\@` isn't a recognized escape at all, so the file
// fails to parse ("invalid escape sequence in literal") the moment Xcode or
// SwiftPM reads it on a Mac — this only surfaces once someone actually
// opens the project there, far from where the bad file was generated.
//
// Package.swift is regenerated by every `cap sync` (its own header says
// "DO NOT MODIFY THIS FILE"), so this doesn't hand-edit content — it just
// normalizes the separator inside `path:` string literals to the forward
// slashes SwiftPM expects on every platform, including Windows itself.
// Safe to run repeatedly; a no-op once the paths are already forward-slash.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const file = 'ios/App/CapApp-SPM/Package.swift'
if (!existsSync(file)) process.exit(0) // no iOS project generated yet

const before = readFileSync(file, 'utf8')
const after = before.replace(/path:\s*"([^"]*)"/g, (m, p) => `path: "${p.replaceAll('\\', '/')}"`)

if (after !== before) {
  writeFileSync(file, after, 'utf8')
  console.log(`fixed backslash paths in ${file}`)
}
