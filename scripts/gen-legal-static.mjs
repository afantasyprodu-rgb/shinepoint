// Generates terms.html and privacy.html — static fallback pages for any
// crawler/reviewer that fetches the site without running JavaScript (e.g.
// Twilio's toll-free verification review). The SPA normally renders these
// routes client-side from Legal.jsx + the `legal.*` strings below; a plain
// fetch of /terms or /privacy would otherwise return the same empty
// index.html shell every other route does.
//
// Runs automatically before every build (see package.json's "build" script)
// — regenerate rather than hand-editing terms.html/privacy.html, or the
// static copy will drift from what Legal.jsx actually renders.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { STRINGS } from '../src/i18n/strings.js'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const L = STRINGS.en.legal
// Mirrors Legal.jsx's UPDATED constant — keep the two in sync by hand;
// they're isolated by design (not worth wiring shared state for one date).
const UPDATED = 'August 2026'

const esc = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

const shell = readFileSync(join(root, 'index.html'), 'utf8')

function build({ file, title, desc, heading, intro, sections, bootstrapApp = true }) {
  const body = [
    `        <h1 style="font-size: 1.5rem; font-weight: 700;">${esc(heading)}</h1>`,
    `        <p style="color: #64748b; font-size: 0.875rem;">${esc(L.lastUpdated.replace('{date}', UPDATED))}</p>`,
    `        <p>${esc(intro)}</p>`,
    ...sections.flatMap(([h, p]) => [
      `        <h2 style="font-size: 1.05rem; font-weight: 700; margin-top: 20px;">${esc(h)}</h2>`,
      `        <p>${esc(p)}</p>`,
    ]),
    `        <p style="margin-top: 24px;">`,
    `          <a href="/" style="color: #de0067;">Home</a>`,
    `          &nbsp;·&nbsp;`,
    `          <a href="/terms" style="color: #de0067;">Terms of Service</a>`,
    `          &nbsp;·&nbsp;`,
    `          <a href="/privacy" style="color: #de0067;">Privacy Policy</a>`,
    `        </p>`,
  ].join('\n')

  const rootBlock = `    <!-- Static fallback content: replaced by React once the bundle mounts,
         but visible to any crawler/reviewer that fetches this page without
         running JavaScript. Generated by scripts/gen-legal-static.mjs from
         src/i18n/strings.js (legal.*) — regenerate (npm run build, or
         node scripts/gen-legal-static.mjs) rather than hand-editing if that
         copy changes. The <head> above must stay byte-identical to
         index.html's: the inline theme script is pinned by a sha256 hash in
         vercel.json's CSP. -->
    <div id="root">
      <main style="max-width: 640px; margin: 0 auto; padding: 32px 20px; font-family: system-ui, sans-serif; color: #1e293b;">
${body}
      </main>
    </div>`

  let out = shell
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)}</title>`)
    .replace(/(<meta name="description" content=")[^"]*(")/, `$1${esc(desc)}$2`)
    // Swap the whole existing #root block (landing fallback) for this page's.
    .replace(/ {4}<!-- Static fallback content:[\s\S]*?\n {4}<\/div>/, rootBlock)

  if (!bootstrapApp) {
    // No matching client route exists for this page (it isn't a real app
    // screen — it exists purely for non-JS/automated readers, e.g. Twilio's
    // toll-free verification crawler). Booting the SPA here would mount
    // React over an unrecognized route and blank the static content out
    // from under a real browser, same as it would blank any route with no
    // <Route> match. Strip every bundle <script> so this page never runs
    // JS at all and the static content is what every visitor — human or
    // crawler — actually sees.
    out = out.replace(/\n\s*<script type="module"[^>]*><\/script>/g, '')
  }

  if (!out.includes(heading)) throw new Error(`root block not swapped for ${file} — check the marker comment in index.html still matches`)
  writeFileSync(join(root, file), out)
  console.log('wrote', file)
}

